"""align PostgreSQL uniqueness metadata with ORM unique indexes

Revision ID: 0016
Revises: 0015
Create Date: 2026-11-11

Several historical migrations declared both ``unique=True`` on a column and a
named unique index for the same key. PostgreSQL materializes those as two
separate uniqueness objects, while the ORM metadata intentionally models the
named unique index. Drop only the redundant autogenerated constraints; the
named unique indexes remain in place and continue enforcing uniqueness.

SQLite reflection already folds these declarations into the metadata shape
used by ``alembic check``, so the migration is deliberately a no-op there.
"""

from typing import Sequence, Union

from alembic import op


revision: str = "0016"
down_revision: Union[str, None] = "0015"
branch_labels: Union[str, Sequence[str], None] = None
depends_on: Union[str, Sequence[str], None] = None


_REDUNDANT_CONSTRAINTS = (
    ("artifacts", "artifacts_action_id_key", ["action_id"]),
    ("artifacts", "artifacts_artifact_ref_key", ["artifact_ref"]),
    ("execution_receipts", "execution_receipts_action_id_key", ["action_id"]),
    ("field_observations", "field_observations_client_id_key", ["client_id"]),
    ("identities", "identities_subject_key", ["subject"]),
    ("twin_profiles", "twin_profiles_slug_key", ["slug"]),
    ("verification_receipts", "verification_receipts_action_id_key", ["action_id"]),
    (
        "verification_receipts",
        "verification_receipts_execution_receipt_id_key",
        ["execution_receipt_id"],
    ),
)


def _is_postgresql() -> bool:
    return op.get_bind().dialect.name == "postgresql"


def upgrade() -> None:
    if not _is_postgresql():
        return
    for table, constraint, _columns in _REDUNDANT_CONSTRAINTS:
        op.drop_constraint(constraint, table, type_="unique")


def downgrade() -> None:
    if not _is_postgresql():
        return
    for table, constraint, columns in _REDUNDANT_CONSTRAINTS:
        op.create_unique_constraint(constraint, table, columns)
